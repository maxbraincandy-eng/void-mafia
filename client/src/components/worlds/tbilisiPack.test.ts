test('every shipped footprint is wound the way the extruder assumes', async () => {
  /*
   * The extruder takes the outward normal of edge a→c to be (dz, −dx), which is
   * only outward if the ring is wound with a positive shoelace area in (x, z).
   * A ring wound the other way builds a building inside out: its walls are
   * culled, you see through it to its own back faces, and nothing throws.
   *
   * Checked against the committed asset rather than a fixture, because the
   * asset is what ships and a regenerate is exactly when this would break.
   */
  const { TBILISI_BUILDINGS_B64, TBILISI_STATS } = await import('./tbilisiData.js');
  const list = unpackBuildings(b64ToBytes(TBILISI_BUILDINGS_B64));
  assert.equal(list.length, TBILISI_STATS.buildings, 'the packed count and the stated count disagree');

  let worst = Infinity;
  for (const b of list) {
    let a2 = 0;
    for (let i = 0, j = b.pts.length - 1; i < b.pts.length; j = i++) {
      a2 += b.pts[j]!.x * b.pts[i]!.z - b.pts[i]!.x * b.pts[j]!.z;
    }
    worst = Math.min(worst, a2 / 2);
  }
  assert.ok(worst > 0, `a footprint is wound backwards (signed area ${worst.toFixed(2)} m²)`);
});

test('the wall normals point away from the building, not into it', async () => {
  /*
   * The same property from the other side, and the one that actually matters:
   * take the extruder's normal for each edge and check it leads away from the
   * footprint's centre. Catches a sign error in the normal itself, which the
   * winding test above would not.
   */
  const { TBILISI_BUILDINGS_B64 } = await import('./tbilisiData.js');
  const list = unpackBuildings(b64ToBytes(TBILISI_BUILDINGS_B64));
  let inward = 0, edges = 0;
  for (const b of list) {
    let cx = 0, cz = 0;
    for (const p of b.pts) { cx += p.x; cz += p.z; }
    cx /= b.pts.length; cz /= b.pts.length;
    for (let i = 0; i < b.pts.length; i++) {
      const a = b.pts[i]!, c = b.pts[(i + 1) % b.pts.length]!;
      const dx = c.x - a.x, dz = c.z - a.z;
      const len = Math.hypot(dx, dz);
      if (len < 0.05) continue;
      edges++;
      const nx = dz / len, nz = -dx / len;
      // From the centroid towards the edge's midpoint.
      const mx = (a.x + c.x) / 2 - cx, mz = (a.z + c.z) / 2 - cz;
      if (nx * mx + nz * mz < 0) inward++;
    }
  }
  /*
   * Not zero: a concave plan — a courtyard, an L around a neighbour — genuinely
   * has edges whose outward normal points back past the centroid, and Old Town
   * is full of them. What would mean a sign error is most of them.
   */
  assert.ok(inward / edges < 0.12,
    `${((100 * inward) / edges).toFixed(1)}% of walls face inward — the normal's sign is wrong`);
});

test('every layer stays inside the district — not just the buildings', async () => {
  /*
   * The bug this is written for, and it cost an afternoon.
   *
   * Overpass returns WHOLE ways, not the part inside the bounding box you
   * asked for. Requesting eight hundred metres of Old Town also returns the
   * entire Mtkvari — a polygon four kilometres across — because one bank of it
   * clips the corner. Packed as int16 decimetres that runs past the ±3276 m the
   * format can hold, and the far points are silently CLAMPED onto the limit.
   *
   * Nothing threw. The river folded into a degenerate spike, three's ear
   * clipper quietly returned a tenth of the faces it should have, and the
   * result was a city with no ground and no water under it — which looked like
   * a lighting problem, then like a winding problem, and was neither.
   *
   * The first version of this test checked buildings only, which is exactly how
   * it got through. Every layer, every time.
   */
  const { TBILISI_BUILDINGS_B64, TBILISI_ROADS_B64, TBILISI_WATER_B64 } = await import('./tbilisiData.js');
  const LIMIT = 760;   // the extractor clips at 700

  const far = (pts: { x: number; z: number }[]) =>
    pts.reduce((m, p) => Math.max(m, Math.abs(p.x), Math.abs(p.z)), 0);

  const b = unpackBuildings(b64ToBytes(TBILISI_BUILDINGS_B64));
  const r = unpackRoads(b64ToBytes(TBILISI_ROADS_B64));
  const w = unpackWater(b64ToBytes(TBILISI_WATER_B64));
  assert.ok(b.length > 400 && r.length > 200 && w.length > 0, 'a layer came back empty');

  for (const [name, layer] of [['buildings', b.map(x => x.pts)], ['roads', r.map(x => x.pts)], ['water', w]] as const) {
    const m = Math.max(...layer.map(far));
    assert.ok(m <= LIMIT, `${name} reach ${m.toFixed(0)} m — past the clip, and near the format's own ceiling`);
  }

  /*
   * And nothing sitting exactly on the packing limit, which is what clamping
   * looks like from the other side: a cluster of points all at 3276.7 m.
   */
  for (const [name, layer] of [['buildings', b.map(x => x.pts)], ['roads', r.map(x => x.pts)], ['water', w]] as const) {
    const pinned = layer.flat().filter(p => Math.abs(Math.abs(p.x) - 3276.7) < 0.2 || Math.abs(Math.abs(p.z) - 3276.7) < 0.2);
    assert.equal(pinned.length, 0, `${name}: ${pinned.length} points are pinned to the int16 limit`);
  }

  const maxH = Math.max(...b.map(x => x.height));
  assert.ok(maxH > 8 && maxH < 102, `tallest building is ${maxH.toFixed(1)} m`);
});
