export function byId(id: string): DumbQuestion | undefined {
  return BANK.find(q => q.id === id);
}

export const QUESTIONS_PER_TEST = 12;

/**
 * Draw a test.
 *
 * `avoid` holds the questions this player has just seen. They are excluded
 * while there are enough others — sixty in the bank against twelve per test
 * means two runs back to back share nothing, which is the whole reason the bank
 * is this size. When the exclusions would leave too few, the rule is dropped
 * rather than returning a short test: a repeat is a small disappointment and a
 * nine-question test is a bug.
 */
export function drawTest(avoid: readonly string[] = []): DumbQuestion[] {
  const blocked = new Set(avoid);
  let pool = BANK.filter(q => !blocked.has(q.id));
  if (pool.length < QUESTIONS_PER_TEST) pool = [...BANK];

  const picked: DumbQuestion[] = [];
  const rest = [...pool];
  for (let i = 0; i < QUESTIONS_PER_TEST && rest.length > 0; i++) {
    picked.push(rest.splice(Math.floor(Math.random() * rest.length), 1)[0]);
  }

  /*
   * Options are shuffled per test, not stored shuffled.
   *
   * Otherwise the correct answer sits at the same index for everyone forever,
   * and the game becomes "remember that the boom barrier one is the first
   * option" — which is a memory test, and a worse one.
   */
  return picked.map(q => {
    const order = q.options.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [order[i], order[j]] = [order[j], order[i]];
    }
    return {
      ...q,
      options: order.map(i => q.options[i]),
      correct: order.indexOf(q.correct),
    };
  });
}

/** Where a score lands. Playful — the game is a joke about itself. */
export function band(correct: number, total: number): { title: string; note: string } {
  const pct = total > 0 ? correct / total : 0;
  if (pct >= 0.92) return { title: 'ეჭვმიტანილი ხარ', note: 'ან ძალიან ჭკვიანი ხარ, ან ეს ტესტი უკვე გაიარე.' };
  if (pct >= 0.75) return { title: 'საეჭვოდ კარგი', note: 'აბსურდის ლოგიკა გესმის. ეს საგანგაშოა.' };
  if (pct >= 0.58) return { title: 'ნორმალური ადამიანი', note: 'ზუსტად შუაში. არც კარგი, არც ცუდი — ყველაზე ცუდი შედეგი.' };
  if (pct >= 0.42) return { title: 'ღირსეული საშუალო', note: 'მონეტის აგდებას ოდნავ ჯობიხარ. ოდნავ.' };
  if (pct >= 0.25) return { title: 'გულწრფელი', note: 'შენ არ იცოდი და არც მოიტყუე. ეს პატივსაცემია.' };
  return { title: 'ლეგენდა', note: 'ამდენი შეცდომა შემთხვევით არ გამოდის. აქ ნიჭია საჭირო.' };
}
